string avl_info::format(double value) const
{
    ostringstream oss;
    oss.precision(max(0, (int)-log10(multiplier)));
    oss << fixed << (value * multiplier) << unit;
    return oss.str();
}

const avl_info& avl_types::get(int type)
{
    auto it = types_.find(type);
    if (it != types_.end()) return it->second;
    static const avl_info unknown{"Unknown", avl_type::hex, 1, ""};
    return unknown;
}

string avl_info::read_value(binary_parser& parser, int size) const
{
    if (size == -1)
    {
        int vlen = parser.read_int16();
        return parser.read_string(vlen);
    }
    return format(parser.read_number(size, type == avl_type::signed_number));
}

